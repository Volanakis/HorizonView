// The previous frontend registered a caching service worker at /sw.js.
// This replacement removes it: browsers fetch the new script, activate it,
// clear the old caches and unregister, so nobody is stuck on stale assets.
self.addEventListener('install', () => self.skipWaiting());

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.map((key) => caches.delete(key)));
    await self.registration.unregister();
    const clients = await self.clients.matchAll({ type: 'window' });
    clients.forEach((client) => client.navigate(client.url));
  })());
});
